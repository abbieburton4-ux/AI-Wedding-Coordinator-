from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = REPO_ROOT / "runway-tracker.xlsx"

# Brand-matched colors (warm ivory + muted gold from the marketing site).
GOLD = "B89047"
IVORY = "FAF8F5"
DARK_GREY = "333333"
HEADER_FONT = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
BODY_FONT = Font(name="Calibri", size=11)
HEADER_FILL = PatternFill("solid", fgColor=GOLD)
ALT_FILL = PatternFill("solid", fgColor=IVORY)
THIN = Side(border_style="thin", color="DDDDDD")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

STATUS_OPTIONS = '"☐ TODO,🟡 WIP,✅ DONE,⛔ BLOCKED"'
CHECK_OPTIONS = '"☐,☑"'


def style_header_row(ws, ncols):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = "A2"


def style_body_rows(ws, ncols, start_row=2):
    for r in range(start_row, ws.max_row + 1):
        for c in range(1, ncols + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = BODY_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER
            if r % 2 == 0:
                cell.fill = ALT_FILL


def set_widths(ws, widths):
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def add_validation(ws, formula1, col_letter, start_row, end_row):
    dv = DataValidation(type="list", formula1=formula1, allow_blank=True)
    dv.error = "Pick from the list"
    dv.errorTitle = "Invalid value"
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}{start_row}:{col_letter}{end_row}")


